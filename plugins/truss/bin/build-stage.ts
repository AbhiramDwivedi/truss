// Builds workflows/stage.js from the modules in workflows-src/stage/. A Workflow script must be one file: factory.ts start copies
// stage.js byte for byte into the session's scripts dir (scriptPathFor), the Workflow gate knows the script by its text, and the
// script may hold no import (ADR-0009). So the modules are plain script parts, not ES modules: each one's first line is a
// `// stage.js module: ...` comment, dropped here, and the rest is joined in STAGE_MODULES order under GENERATED_HEADER.
// The modules sit outside workflows/: plugin.json declares no workflows, so Claude Code might scan that dir, and a part has no
// meta export. Node built-ins only, no clock, `\n` line ends on every platform, so a build is the same bytes everywhere.
//
//   node plugins/truss/bin/build-stage.ts            writes plugins/truss/workflows/stage.js (npm run build:stage)
//   node plugins/truss/bin/build-stage.ts --out F    writes F instead
//   node plugins/truss/bin/build-stage.ts --check    exits 1 when the committed stage.js is not what a build writes
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

/** The modules, in bundle order. The order is the old single file's order, so the bundle runs the same code as before the split. */
export const STAGE_MODULES = [
  'args',
  'texts',
  'globs',
  'schemas',
  'spawn',
  'crew',
  'runner',
  'gates',
  'answers',
  'check',
  'prompts',
  'members',
  'calls',
  'replies',
  'integrate',
  'tasks',
  'ruling',
  'fixes',
  'split',
  'green',
  'stress',
  'scope',
  'qc-context',
  'knowledge',
  'lint',
  'qc',
  'ux',
  'chain',
]

/** The bundle's first line. bin/testmap.ts reads "from the modules in ../workflows-src/stage/" to send a module's change to stage.js's tests. */
export const GENERATED_HEADER = '// Generated by `npm run build:stage` (bin/build-stage.ts) from the modules in ../workflows-src/stage/. Edit those and rebuild; never edit this file.\n'
const MODULE_HEAD = /^\/\/ stage\.js module: [^\n]*\n/

export const WORKFLOWS_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'workflows')
export const STAGE_SRC_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'workflows-src', 'stage')

/** The bundle text for the modules in `srcDir` (default workflows-src/stage/). Throws on a module missing from the dir or from STAGE_MODULES. */
export function buildStage(srcDir: string = STAGE_SRC_DIR): string {
  const dir = srcDir
  const found = readdirSync(dir).filter((f) => f.endsWith('.js'))
  const listed = STAGE_MODULES.map((m) => `${m}.js`)
  const extra = found.filter((f) => !listed.includes(f)).sort()
  const missing = listed.filter((f) => !found.includes(f))
  if (extra.length) throw new Error(`not in STAGE_MODULES (bin/build-stage.ts): ${extra.join(', ')}`)
  if (missing.length) throw new Error(`missing from ${dir}: ${missing.join(', ')}`)
  let out = GENERATED_HEADER
  for (const f of listed) {
    const text = readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n')
    if (!MODULE_HEAD.test(text)) throw new Error(`${f}: the first line must be a "// stage.js module: ..." comment`)
    const body = text.replace(MODULE_HEAD, '')
    if (!body.endsWith('\n')) throw new Error(`${f}: must end with a newline`)
    out += body
  }
  return out
}

/** The top-level names a script body declares: function, class, const, let and var at column 0 (stage modules are formatted so). */
function declaredNames(body: string): string[] {
  const names = new Set<string>()
  for (const m of body.matchAll(/^(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)|^class\s+([A-Za-z_$][\w$]*)|^(?:const|let|var)\s+([A-Za-z_$][\w$]*)/gm)) names.add((m[1] ?? m[2] ?? m[3]) as string)
  return [...names]
}

/** Runs a script body as an AsyncFunction whose parameters are the stub names, and returns what it declares at top level. */
async function runBody(body: string, stubs: Record<string, unknown>): Promise<Record<string, unknown>> {
  const names = declaredNames(body)
  const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor
  const fn = new AsyncFunction(...Object.keys(stubs), `${body}\n;return { ${names.join(', ')} }`)
  return (await fn(...Object.values(stubs))) as Record<string, unknown>
}

/** Loads one workflows-src/stage/ module alone, for a single-step test (ADR-0050). Every free name the module uses and does not
 * declare must be in `stubs` (`agent`, `args`, `log`, the runner calls); a missing one throws a ReferenceError when reached. Returns
 * the module's top-level declarations as `scope`. */
export async function loadStageStep(file: string, stubs: Record<string, unknown> = {}): Promise<{ loaded: string[]; scope: Record<string, unknown> }> {
  const abs = path.resolve(file)
  const rel = path.relative(STAGE_SRC_DIR, abs)
  if (rel.startsWith('..') || path.isAbsolute(rel) || !abs.endsWith('.js')) throw new Error(`${file} is not a module in ${STAGE_SRC_DIR}`)
  const text = readFileSync(abs, 'utf8').replace(/\r\n/g, '\n')
  if (!MODULE_HEAD.test(text)) throw new Error(`${file}: the first line must be a "// stage.js module: ..." comment`)
  const body = text.replace(MODULE_HEAD, '').replace(/^export\s+/gm, '')
  return { loaded: [abs], scope: await runBody(body, stubs) }
}

/** Loads the committed workflows/stage.js with the same stubs, without running the stage: `meta` is not exported and the top-level
 * run (`const results = await Promise.all(F.crews.map(runCrew))` and what follows) is cut off. */
export async function loadStageBundle(stubs: Record<string, unknown> = {}): Promise<{ loaded: string[]; scope: Record<string, unknown> }> {
  const file = path.join(WORKFLOWS_DIR, 'stage.js')
  const text = readFileSync(file, 'utf8').replace(/\r\n/g, '\n')
  const run = 'const results = await Promise.all(F.crews.map(runCrew))'
  const at = text.indexOf(`\n${run}`)
  if (at < 0) throw new Error(`${file}: the top-level run line "${run}" was not found`)
  const body = text.slice(0, at + 1).replace(/^export\s+/gm, '')
  // the bundle stops at load when args.truss is not an object (args.js) and reads F.dir while it loads (RUN_KEY); a test that has no
  // crew to run gets an args.truss with no crews, so the same load works
  const a = stubs.args
  const seeded = a && typeof a === 'object' && !Array.isArray(a) && !('truss' in a) ? { ...stubs, args: { ...a, truss: { dir: '/', repo: '/' } } } : stubs
  return { loaded: [file], scope: await runBody(body, seeded) }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2)
  const target = path.join(WORKFLOWS_DIR, 'stage.js')
  try {
    const text = buildStage()
    if (argv[0] === '--check') {
      const same = readFileSync(target, 'utf8') === text
      console.log(same ? 'stage.js matches its modules' : 'stage.js is out of date: run npm run build:stage')
      process.exit(same ? 0 : 1)
    }
    const out = argv[0] === '--out' && argv[1] ? path.resolve(argv[1]) : target
    writeFileSync(out, text)
    console.log(`wrote ${out}`)
  } catch (err) {
    console.error(err instanceof Error ? err.message : String(err))
    process.exit(2)
  }
}
