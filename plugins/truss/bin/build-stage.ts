// Builds workflows/stage.js from the modules in workflows-src/stage/. A Workflow script must be one file: factory.ts start copies
// stage.js byte for byte into the session's scripts dir (scriptPathFor), the Workflow gate knows the script by its text, and the
// script may hold no import (ADR-0009). So the modules are plain script parts, not ES modules: each one's first line is a
// `// stage.js module: ...` comment, dropped here, and the rest is joined in STAGE_MODULES order under GENERATED_HEADER.
// The modules sit outside workflows/: plugin.json declares no workflows, so Claude Code might scan that dir, and a part has no
// meta export. Node built-ins only, no clock, `\n` line ends on every platform, so a build is the same bytes everywhere.
//
//   node plugins/truss/bin/build-stage.ts            writes plugins/truss/workflows/stage.js (npm run build:stage)
//   node plugins/truss/bin/build-stage.ts --out F    writes F instead
//   node plugins/truss/bin/build-stage.ts --check    exits 1 when the committed stage.js is not what a build writes
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

/** The modules, in bundle order. The order is the old single file's order, so the bundle runs the same code as before the split. */
export const STAGE_MODULES = [
  'args',
  'texts',
  'globs',
  'schemas',
  'spawn',
  'crew',
  'runner',
  'gates',
  'answers',
  'check',
  'prompts',
  'members',
  'calls',
  'replies',
  'integrate',
  'tasks',
  'ruling',
  'fixes',
  'split',
  'green',
  'stress',
  'scope',
  'qc-context',
  'knowledge',
  'lint',
  'qc',
  'ux',
  'chain',
]

/** The bundle's first line. bin/testmap.ts reads "from the modules in ../workflows-src/stage/" to send a module's change to stage.js's tests. */
export const GENERATED_HEADER = '// Generated by `npm run build:stage` (bin/build-stage.ts) from the modules in ../workflows-src/stage/. Edit those and rebuild; never edit this file.\n'
const MODULE_HEAD = /^\/\/ stage\.js module: [^\n]*\n/

export const WORKFLOWS_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'workflows')
export const STAGE_SRC_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'workflows-src', 'stage')

/** The bundle text for the modules in `srcDir` (default workflows-src/stage/). Throws on a module missing from the dir or from STAGE_MODULES. */
export function buildStage(srcDir: string = STAGE_SRC_DIR): string {
  const dir = srcDir
  const found = readdirSync(dir).filter((f) => f.endsWith('.js'))
  const listed = STAGE_MODULES.map((m) => `${m}.js`)
  const extra = found.filter((f) => !listed.includes(f)).sort()
  const missing = listed.filter((f) => !found.includes(f))
  if (extra.length) throw new Error(`not in STAGE_MODULES (bin/build-stage.ts): ${extra.join(', ')}`)
  if (missing.length) throw new Error(`missing from ${dir}: ${missing.join(', ')}`)
  let out = GENERATED_HEADER
  for (const f of listed) {
    const text = readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n')
    if (!MODULE_HEAD.test(text)) throw new Error(`${f}: the first line must be a "// stage.js module: ..." comment`)
    const body = text.replace(MODULE_HEAD, '')
    if (!body.endsWith('\n')) throw new Error(`${f}: must end with a newline`)
    out += body
  }
  return out
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2)
  const target = path.join(WORKFLOWS_DIR, 'stage.js')
  try {
    const text = buildStage()
    if (argv[0] === '--check') {
      const same = readFileSync(target, 'utf8') === text
      console.log(same ? 'stage.js matches its modules' : 'stage.js is out of date: run npm run build:stage')
      process.exit(same ? 0 : 1)
    }
    const out = argv[0] === '--out' && argv[1] ? path.resolve(argv[1]) : target
    writeFileSync(out, text)
    console.log(`wrote ${out}`)
  } catch (err) {
    console.error(err instanceof Error ? err.message : String(err))
    process.exit(2)
  }
}
